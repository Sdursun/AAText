#!/usr/bin/env python3
"""
Generate the freetype2.library function table and client headers from
src/aatext.funcs.

  genfuncs.py <funcs> <outdir-src-gen> <outdir-include>

Writes
  <gen>/functable.inc            LIBFUNC()/LIBSKIP() lines, LVO -30 on
  <inc>/fd/aatext_lib.fd
  <inc>/clib/aatext_protos.h  bullet API prototypes
  <inc>/inline/aatext.h       calls through the library base
  <inc>/proto/aatext.h
and prints the LVO map to stdout.
"""

import os
import re
import sys

FIRST_LVO = 5           # after Open, Close, Expunge, Reserved
BASE = "AATextBase"

PROTO_RE = re.compile(r'^(?P<ret>.*?)\b(?P<name>\w+)\s*\((?P<args>[^()]*)\)'
                      r'\s*(?:\((?P<regs>[^()]*)\))?\s*$')


class Func:
    def __init__(self, ret, name, args, regs):
        self.ret = ret.strip()
        self.name = name
        self.args = args            # list of (decl, type, argname)
        self.regs = regs            # None: stack call


def parse_arg(decl):
    decl = decl.strip()
    names = re.findall(r'[A-Za-z_]\w*', decl)
    if not names:
        raise ValueError("bad argument: " + decl)
    argname = names[-1]
    # remove the last occurrence of the name: what is left is the type
    i = decl.rfind(argname)
    typ = (decl[:i] + decl[i + len(argname):]).strip()
    typ = re.sub(r'\s+', ' ', typ)
    return (decl, typ, argname)


def parse(path):
    entries = []
    with open(path, encoding="latin-1") as f:
        for lineno, line in enumerate(f, 1):
            line = line.split('#', 1)[0].strip()
            if not line:
                continue
            if line.startswith('.skip'):
                entries.extend([None] * int(line.split()[1]))
                continue
            m = PROTO_RE.match(line)
            if not m:
                sys.exit("%s:%d: cannot parse: %s" % (path, lineno, line))
            args = m.group('args').strip()
            arglist = [] if args in ('', 'void') else \
                [parse_arg(a) for a in args.split(',')]
            regs = m.group('regs')
            if regs is not None:
                regs = [r.strip().lower() for r in regs.split(',') if r.strip()]
                if len(regs) != len(arglist):
                    sys.exit("%s:%d: register count mismatch" % (path, lineno))
            entries.append(Func(m.group('ret'), m.group('name'), arglist, regs))
    return entries


def lvo(index):
    return (FIRST_LVO + index) * 6


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="latin-1", newline="\n") as f:
        f.write(text)


HEADER = "/* Generated by tools/genfuncs.py from src/aatext.funcs - do not edit. */\n"


def gen_functable(entries):
    out = [HEADER]
    for i, e in enumerate(entries):
        if e is None:
            out.append("LIBSKIP()                /* -%d */\n" % lvo(i))
        elif e.regs is not None:
            out.append("LIBFUNC(LIB_%s)  /* -%d */\n" % (e.name, lvo(i)))
        else:
            out.append("LIBFUNC(%s)  /* -%d */\n" % (e.name, lvo(i)))
    return "".join(out)


def gen_fd(entries):
    out = ["* freetype2.library\n",
           "* Generated by tools/genfuncs.py - do not edit.\n",
           "*\n",
           "* The FreeType functions (from FT_Init_FreeType on) take their\n",
           "* arguments on the stack in C order, not in registers. They are\n",
           "* marked private here so that fd tools do not make register calls\n",
           "* for them; use <proto/aatext.h> (C) instead.\n",
           "##base _%s\n" % BASE,
           "##bias 30\n"]
    public = None
    for i, e in enumerate(entries):
        if e is None:
            name, args, regs, pub = "ft2Reserved%d" % lvo(i), "", "", False
        else:
            name = e.name
            args = ",".join(a[2] for a in e.args)
            if e.regs is not None:
                regs, pub = ",".join(r.upper() for r in e.regs), True
            else:
                regs, pub = "", False
        if pub != public:
            out.append("##public\n" if pub else "##private\n")
            public = pub
        out.append("%s(%s)(%s)\n" % (name, args, regs))
    out.append("##end\n")
    return "".join(out)


def gen_clib(entries):
    out = [HEADER,
           "#ifndef CLIB_AATEXT_PROTOS_H\n#define CLIB_AATEXT_PROTOS_H\n\n",
           "/*\n * The bullet.library API of freetype2.library. The FreeType API\n",
           " * is declared by the FreeType headers themselves.\n */\n\n",
           "#include <exec/types.h>\n#include <utility/tagitem.h>\n",
           "#include <diskfont/glyph.h>\n\n"]
    for e in entries:
        if e is not None and e.regs is not None:
            args = ", ".join(a[0] for a in e.args) or "void"
            out.append("%s %s(%s);\n" % (e.ret, e.name, args))
    out.append("\n#endif\n")
    return "".join(out)


def gen_inline(entries):
    out = [HEADER,
           "#ifndef _INLINE_AATEXT_H\n#define _INLINE_AATEXT_H\n\n",
           "/*\n",
           " * Calls into freetype2.library for gcc. Include <proto/aatext.h>,\n",
           " * which includes the FreeType headers first: these macros must come\n",
           " * after the FreeType prototypes they replace.\n",
           " *\n",
           " * The FreeType functions take their arguments on the stack; a call\n",
           " * jumps through the library vector like a normal C function call.\n",
           " */\n\n",
           "#ifndef __INLINE_MACROS_H\n#include <inline/macros.h>\n#endif\n\n",
           "#ifndef AATEXT_BASE_NAME\n#define AATEXT_BASE_NAME %s\n#endif\n\n" % BASE,
           "#define AATEXT_LVO_(off) ((void *)((char *)(AATEXT_BASE_NAME) - (off)))\n\n"]
    for i, e in enumerate(entries):
        if e is None:
            continue
        off = lvo(i)
        params = ", ".join("p%d" % (n + 1) for n in range(len(e.args)))
        if e.regs is not None:
            n = len(e.args)
            ret = e.ret
            isvoid = ret == "void"
            macro = ("LP%d%s" % (n, "NR" if isvoid else ""))
            parts = [str(off)]
            if not isvoid:
                parts.append(ret)
            parts.append(e.name)
            for k, a in enumerate(e.args):
                parts += [a[1], "p%d" % (k + 1), e.regs[k]]
            parts += ["\\\n\tstruct Library *", "AATEXT_BASE_NAME"]
            out.append("#define %s(%s) \\\n\t%s(%s)\n\n" %
                       (e.name, params, macro, ", ".join(parts)))
        else:
            types = ", ".join(a[1] for a in e.args) or "void"
            call = ", ".join("(p%d)" % (n + 1) for n in range(len(e.args)))
            out.append("#define %s(%s) \\\n\t(((%s (*)(%s))AATEXT_LVO_(%d))(%s))\n\n" %
                       (e.name, params, e.ret, types, off, call))
    out.append("#endif\n")
    return "".join(out)


def gen_proto(includes):
    return (HEADER +
            "#ifndef PROTO_AATEXT_H\n#define PROTO_AATEXT_H\n\n"
            "#include <exec/types.h>\n"
            "#include <libraries/aatext.h>\n"
            + "".join("#include %s\n" % h for h in includes) +
            "\n#ifndef __NOLIBBASE__\nextern struct Library *%s;\n#endif\n\n"
            "#include <clib/aatext_protos.h>\n\n"
            "#if defined(__GNUC__) && !defined(AATEXT_NO_INLINE)\n"
            "#include <inline/aatext.h>\n"
            "#endif\n\n"
            "#endif\n" % BASE)


FT_INCLUDES = [
    "<ft2build.h>",
    "FT_FREETYPE_H", "FT_GLYPH_H", "FT_IMAGE_H", "FT_SYSTEM_H", "FT_TYPES_H",
    "FT_CACHE_H", "FT_TRIGONOMETRY_H", "FT_MODULE_H", "FT_LIST_H",
    "FT_TRUETYPE_TABLES_H", "FT_SFNT_NAMES_H", "FT_COLOR_H", "FT_OUTLINE_H",
    "FT_STROKER_H", "FT_LCD_FILTER_H", "FT_MULTIPLE_MASTERS_H",
    "FT_SYNTHESIS_H", "FT_BBOX_H", "FT_BITMAP_H", "FT_ADVANCES_H",
    "FT_GZIP_H", "FT_FONT_FORMATS_H", "FT_DRIVER_H", "FT_SIZES_H",
    "FT_RENDER_H", "FT_PARAMETER_TAGS_H",
]


def main():
    funcs, gendir, incdir = sys.argv[1:4]
    entries = parse(funcs)
    write(os.path.join(gendir, "functable.inc"), gen_functable(entries))
    write(os.path.join(incdir, "fd", "aatext_lib.fd"), gen_fd(entries))
    write(os.path.join(incdir, "clib", "aatext_protos.h"), gen_clib(entries))
    write(os.path.join(incdir, "inline", "aatext.h"), gen_inline(entries))
    write(os.path.join(incdir, "proto", "aatext.h"), gen_proto(FT_INCLUDES))
    for i, e in enumerate(entries):
        print("-%-4d %s" % (lvo(i), e.name if e else "(reserved)"))


if __name__ == "__main__":
    main()
