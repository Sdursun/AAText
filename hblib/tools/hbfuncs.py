#!/usr/bin/env python3
"""
Generate harfbuzz.library's function table, call wrappers and client
headers from src/harfbuzz.funcs.

  hbfuncs.py <funcs> <outdir-src-gen> <outdir-include>

Writes
  <gen>/functable.inc            LIBFUNC() lines, LVO -30 on
  <gen>/wrappers.c               one wrapper per function: arguments into
                                 a struct, hb_Call() (semaphore, stack),
                                 result back
  <inc>/fd/harfbuzz_lib.fd
  <inc>/inline/harfbuzz.h        calls through the library base
  <inc>/proto/harfbuzz.h
and prints the LVO map to stdout.

All functions take their arguments on the stack in C order, as declared
in HarfBuzz's headers; the wrapper is a normal C function with the same
prototype.
"""

import os
import re
import sys

FIRST_LVO = 5           # after Open, Close, Expunge, Reserved
BASE = "HarfBuzzBase"

PROTO_RE = re.compile(r'^(?P<ret>.*?)\b(?P<name>\w+)\s*\((?P<args>.*)\)\s*$')


class Func:
    def __init__(self, ret, name, args):
        self.ret = re.sub(r'\s+', ' ', ret.strip())
        self.name = name
        self.args = args        # list of (type, decl with pN as the name)


def parse_arg(decl, n):
    decl = decl.strip()
    names = re.findall(r'[A-Za-z_]\w*', decl)
    if not names:
        raise ValueError("bad argument: " + decl)
    argname = names[-1]
    i = decl.rfind(argname)
    typ = re.sub(r'\s+', ' ', (decl[:i] + decl[i + len(argname):]).strip())
    pdecl = decl[:i] + "p%d" % n + decl[i + len(argname):]
    return (typ, pdecl)


def parse(path):
    funcs = []
    with open(path, encoding="latin-1") as f:
        for lineno, line in enumerate(f, 1):
            line = line.split('#', 1)[0].strip()
            if not line:
                continue
            m = PROTO_RE.match(line)
            if not m:
                sys.exit("%s:%d: cannot parse: %s" % (path, lineno, line))
            args = m.group('args').strip()
            arglist = [] if args in ('', 'void') else \
                [parse_arg(a, k + 1) for k, a in enumerate(args.split(','))]
            funcs.append(Func(m.group('ret'), m.group('name'), arglist))
    return funcs


def lvo(index):
    return (FIRST_LVO + index) * 6


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="latin-1", newline="\n") as f:
        f.write(text)


HEADER = "/* Generated by tools/hbfuncs.py from src/harfbuzz.funcs - do not edit. */\n"


def gen_functable(funcs):
    return HEADER + "".join("LIBFUNC(W_%s)  /* -%d */\n" % (f.name, lvo(i))
                            for i, f in enumerate(funcs))


def gen_wrappers(funcs):
    out = [HEADER,
           "/*\n * One wrapper per library function: the arguments go into a\n"
           " * struct, hb_Call() runs the thunk under the library's semaphore\n"
           " * (on a bigger stack if the caller's is low), the result comes back.\n"
           " */\n\n",
           "#include <hb.h>\n#include <hb-ot.h>\n\n#include \"../lib.h\"\n\n"]
    for f in funcs:
        void = f.ret == "void"
        members = [d for _, d in f.args]
        if not void:
            members.append("%s r" % f.ret if not f.ret.endswith('*')
                           else "%sr" % f.ret)
        if not members:
            members.append("int unused")
        call = "%s(%s)" % (f.name, ", ".join("a->p%d" % (k + 1)
                                             for k in range(len(f.args))))
        params = ", ".join(d for _, d in f.args) or "void"
        out.append("struct A_%s\n{\n%s};\n\n" %
                   (f.name, "".join("    %s;\n" % m for m in members)))
        out.append("static ULONG T_%s(APTR arg)\n{\n" % f.name)
        out.append("    struct A_%s *a = arg;\n\n" % f.name)
        if f.args or not void:
            pass
        out.append("    %s%s;\n" % ("" if void else "a->r = ", call))
        if not f.args and void:
            out.append("    (void)a;\n")
        out.append("    return 0;\n}\n\n")
        out.append("%s W_%s(%s)\n{\n    struct A_%s a;\n\n" %
                   (f.ret, f.name, params, f.name))
        for k in range(len(f.args)):
            out.append("    a.p%d = p%d;\n" % (k + 1, k + 1))
        out.append("    hb_Call(T_%s, &a);\n" % f.name)
        if not void:
            out.append("    return a.r;\n")
        out.append("}\n\n")
    return "".join(out)


def gen_fd(funcs):
    out = ["* harfbuzz.library\n",
           "* Generated by tools/hbfuncs.py - do not edit.\n",
           "*\n",
           "* All functions take their arguments on the stack in C order, not\n",
           "* in registers. They are marked private here so that fd tools do\n",
           "* not make register calls for them; use <proto/harfbuzz.h> (C).\n",
           "##base _%s\n" % BASE,
           "##bias 30\n",
           "##private\n"]
    for f in funcs:
        out.append("%s(%s)()\n" % (f.name, ",".join("p%d" % (k + 1)
                                                     for k in range(len(f.args)))))
    out.append("##end\n")
    return "".join(out)


def gen_inline(funcs):
    out = [HEADER,
           "#ifndef _INLINE_HARFBUZZ_H\n#define _INLINE_HARFBUZZ_H\n\n",
           "/*\n",
           " * Calls into harfbuzz.library for gcc. Include <proto/harfbuzz.h>,\n",
           " * which includes <hb.h> and <hb-ot.h> first: these macros must come\n",
           " * after the HarfBuzz prototypes they replace.\n",
           " *\n",
           " * The functions take their arguments on the stack; a call jumps\n",
           " * through the library vector like a normal C function call.\n",
           " */\n\n",
           "#ifndef HARFBUZZ_BASE_NAME\n#define HARFBUZZ_BASE_NAME %s\n#endif\n\n" % BASE,
           "#define HARFBUZZ_LVO_(off) ((void *)((char *)(HARFBUZZ_BASE_NAME) - (off)))\n\n"]
    for i, f in enumerate(funcs):
        params = ", ".join("p%d" % (k + 1) for k in range(len(f.args)))
        types = ", ".join(t for t, _ in f.args) or "void"
        call = ", ".join("(p%d)" % (k + 1) for k in range(len(f.args)))
        out.append("#define %s(%s) \\\n\t(((%s (*)(%s))HARFBUZZ_LVO_(%d))(%s))\n\n" %
                   (f.name, params, f.ret, types, lvo(i), call))
    out.append("#endif\n")
    return "".join(out)


def gen_proto():
    return (HEADER +
            "#ifndef PROTO_HARFBUZZ_H\n#define PROTO_HARFBUZZ_H\n\n"
            "#include <exec/types.h>\n"
            "#include <hb.h>\n#include <hb-ot.h>\n"
            "\n#ifndef __NOLIBBASE__\nextern struct Library *%s;\n#endif\n\n"
            "#if defined(__GNUC__) && !defined(HARFBUZZ_NO_INLINE)\n"
            "#include <inline/harfbuzz.h>\n"
            "#endif\n\n"
            "#endif\n" % BASE)


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    funcs = parse(sys.argv[1])
    gen, inc = sys.argv[2], sys.argv[3]
    write(os.path.join(gen, "functable.inc"), gen_functable(funcs))
    write(os.path.join(gen, "wrappers.c"), gen_wrappers(funcs))
    write(os.path.join(inc, "fd", "harfbuzz_lib.fd"), gen_fd(funcs))
    write(os.path.join(inc, "inline", "harfbuzz.h"), gen_inline(funcs))
    write(os.path.join(inc, "proto", "harfbuzz.h"), gen_proto())
    for i, f in enumerate(funcs):
        print("-%-5d %s" % (lvo(i), f.name))


if __name__ == "__main__":
    main()
